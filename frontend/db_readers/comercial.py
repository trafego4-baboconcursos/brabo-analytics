# tipo do DDL -> data_type do information_schema
_TIPOS = {"text": "text", "integer": "integer", "boolean": "boolean", "numeric": "numeric",
          "date": "date", "timestamptz": "timestamp with time zone", "text[]": "ARRAY",
          "bigserial": "bigint", "jsonb": "jsonb"}
_NAO_COLUNA = {"PRIMARY", "CHECK", "UNIQUE", "CONSTRAINT", "FOREIGN"}
_RE_CREATE = re.compile(r"\s*CREATE TABLE IF NOT EXISTS (\w+)\s*\(")


def colunas_do_ddl() -> dict[str, dict[str, str]]:
    """{tabela: {coluna: data_type do information_schema}} tirado do próprio DDL."""
    out: dict[str, dict[str, str]] = {}
    for ddl in DDL:
        m = _RE_CREATE.match(ddl)
        if not m:
            continue
        corpo = re.sub(r"--[^\n]*", "", ddl[m.end():ddl.rstrip().rfind(")")])
        partes, nivel, atual = [], 0, ""
        for ch in corpo:
            nivel += (ch == "(") - (ch == ")")
            if ch == "," and nivel == 0:
                partes.append(atual)
                atual = ""
            else:
                atual += ch
        partes.append(atual)
        cols: dict[str, str] = {}
        for p in partes:
            toks = p.split()
            if not toks or toks[0].upper() in _NAO_COLUNA:
                continue
            cols[toks[0]] = _TIPOS[toks[1].lower()]
        out[m.group(1)] = cols
    return out


def divergencias_de_colunas(existentes: dict[str, dict[str, str]]) -> list[str]:
    """Diferenças entre as comercial_* que já existem no banco e o DDL (tabela que não
    existe ainda não é divergência: o CREATE vai criá-la)."""
    dif: list[str] = []
    for tabela, esperado in colunas_do_ddl().items():
        atual = existentes.get(tabela)
        if not atual:
            continue
        for c in sorted(set(esperado) - set(atual)):
            dif.append(f"{tabela}: falta a coluna {c}")
        for c in sorted(set(atual) - set(esperado)):
            dif.append(f"{tabela}: coluna {c} não está no DDL")
        for c in sorted(set(esperado) & set(atual)):
            if esperado[c] != atual[c]:
                dif.append(f"{tabela}: coluna {c} é {atual[c]}, DDL diz {esperado[c]}")
    return dif


_SQL_COLUNAS = ("SELECT table_name, column_name, data_type FROM information_schema.columns "
                "WHERE table_schema = current_schema() AND table_name = ANY(:t)")


def conferir_colunas(conn) -> None:
    """Aborta (RuntimeError) se alguma comercial_* já existe com colunas diferentes do DDL:
    `CREATE TABLE IF NOT EXISTS` não migra tabela existente."""
    existentes: dict[str, dict[str, str]] = {}
    for t, c, tipo in conn.execute(text(_SQL_COLUNAS), {"t": sorted(colunas_do_ddl())}).fetchall():
        existentes.setdefault(t, {})[c] = tipo
    dif = divergencias_de_colunas(existentes)
    if dif:
        raise RuntimeError("tabelas comercial_* já existem com colunas diferentes do DDL; "
                           "nada foi gravado:\n  " + "\n  ".join(dif))


_RE_ALVO = re.compile(r"\b(?:INTO|TABLE|UPDATE|FROM|JOIN|ON)\s+(?:IF\s+NOT\s+EXISTS\s+)?([A-Za-z_][\w.]*)",
                      re.IGNORECASE)
_LIBERADAS = {"information_schema.columns"}
# lista de permissão: só estas formas de comando passam (UPDATE/DELETE das telas, quando
# vierem, entram como forma explícita aqui — não por exceção na lista de proibidas)
_PROIBIDAS = re.compile(r"\b(?:DELETE|DROP|TRUNCATE|ALTER|GRANT|REVOKE|UPDATE|WITH|COPY|"
                        r"REFERENCES|RETURNING)\b|\bpg_", re.IGNORECASE)
_FORMAS = [
    re.compile(r"\s*CREATE\s+TABLE\s+IF\s+NOT\s+EXISTS\s+comercial_\w+\s*\(", re.IGNORECASE),
    re.compile(r"\s*CREATE\s+(?:UNIQUE\s+)?INDEX\s+IF\s+NOT\s+EXISTS\s+\w+\s+ON\s+comercial_\w+\s*\(",
               re.IGNORECASE),
    re.compile(r"\s*INSERT\s+INTO\s+comercial_\w+\s*\(", re.IGNORECASE),
]
# Escritas com UPDATE/ON CONFLICT entram como declaração EXATA (comparada após normalizar
# espaços); qualquer variação é recusada pela lista de permissão normal.
SQL_SNAPSHOT_UPSERT = (
    "INSERT INTO comercial_snapshot (mes, gerado_em, linhas, alertas, desatualizado) "
    "VALUES (:mes, :gerado_em, CAST(:linhas AS jsonb), CAST(:alertas AS jsonb), false) "
    "ON CONFLICT (mes) DO UPDATE SET gerado_em = EXCLUDED.gerado_em, linhas = EXCLUDED.linhas, "
    "alertas = EXCLUDED.alertas, desatualizado = false")
SQL_SNAPSHOT_DESATUALIZAR_MES = (
    "UPDATE comercial_snapshot SET desatualizado = true WHERE mes = :mes")
SQL_SNAPSHOT_DESATUALIZAR_TODOS = (
    "UPDATE comercial_snapshot SET desatualizado = true WHERE desatualizado = false")
_EXATAS = {" ".join(q.split()) for q in
           (SQL_SNAPSHOT_UPSERT, SQL_SNAPSHOT_DESATUALIZAR_MES, SQL_SNAPSHOT_DESATUALIZAR_TODOS)}
_SELECT_COUNT = re.compile(r"\s*SELECT\s+count\(\*\)\s+FROM\s+comercial_\w+\s*", re.IGNORECASE)
_INSERT_COM_LEITURA = re.compile(r"\b(?:SELECT|FROM|JOIN|TABLE)\b", re.IGNORECASE)


def exigir_so_comercial(sql: str) -> None:
    """Guarda da gravação (lista de permissão). Passa só: CREATE TABLE/INDEX IF NOT EXISTS
    em comercial_*, INSERT INTO comercial_* (sem SELECT/FROM), SELECT count(*) FROM
    comercial_* e a consulta de colunas do information_schema. Recusa `;` (um final é
    tolerado), aspas duplas e DELETE/DROP/TRUNCATE/ALTER/GRANT/REVOKE/UPDATE/WITH/COPY/pg_
    em qualquer ponto."""
    s = sql.strip()
    if s.endswith(";"):
        s = s[:-1]
    if " ".join(s.split()) in _EXATAS:
        return

    def recusa(motivo: str):
        raise RuntimeError(f"gravação do comercial recusou ({motivo}): {sql[:80]!r}")

    if ";" in s:
        recusa("mais de um comando")
    if '"' in s:
        recusa("identificador entre aspas")
    if _PROIBIDAS.search(s):
        recusa("palavra proibida")
    if s == _SQL_COLUNAS.strip() or _SELECT_COUNT.fullmatch(s):
        return
    if not any(f.match(s) for f in _FORMAS):
        recusa("forma de comando fora da lista")
    if _FORMAS[2].match(s) and _INSERT_COM_LEITURA.search(s):
        recusa("INSERT lendo de tabela")
    # segunda camada: toda tabela citada é comercial_*
    alvos = [a for a in _RE_ALVO.findall(s) if a.upper() != "CONFLICT"]
    fora = [a for a in alvos if not a.lower().startswith("comercial_") and a.lower() not in _LIBERADAS]
    if not alvos or fora:
        recusa(f"tabela fora de comercial_*: {fora}")


def criar_tabelas(conn=None) -> None:
    """Confere as colunas das comercial_* existentes e cria as que faltam (idempotente).
    Só quem grava chama. Com `conn`, roda dentro da transação de quem chamou."""
    if conn is None:
        with _get_users_engine().begin() as c:
            return criar_tabelas(c)
    conferir_colunas(conn)
    for ddl in DDL:
        exigir_so_comercial(ddl)
        conn.execute(text(ddl))


_RE_SEM_TABELA = re.compile(r'(?<!of )relation "comercial_\w+" does not exist')


def tabela_comercial_ausente(exc: BaseException) -> bool:
    """True só para "relation \"comercial_...\" does not exist" (tabela ainda não criada).
    Erro de coluna, ou de outra tabela, é falso: tem de estourar."""
    codigo = getattr(getattr(exc, "orig", None), "pgcode", None)
    if codigo is not None and codigo != "42P01":
        return False
    return bool(_RE_SEM_TABELA.search(str(getattr(exc, "orig", None) or exc)))


def _regra_da_linha(r) -> RegraPercentual:
    """Linha do SELECT (ordem da dataclass) -> RegraPercentual; `categorias` text[] -> frozenset."""
    *campos, categorias, forca_tipo = r
    return RegraPercentual(*campos, frozenset(categorias) if categorias is not None else None,
                           forca_tipo)


def ler_cadastros() -> Cadastros:
    """Cadastros vigentes. Tabela ausente -> Cadastros vazio + warning (sem DDL)."""
    try:
        with _get_users_engine().connect() as conn:
            vend = conn.execute(text("SELECT codigo, nome FROM comercial_vendedores")).fetchall()
            regras = conn.execute(text(
                "SELECT id, plataforma, modalidade, tipo, pct, vendedor_codigo, vigente_de, vigente_ate, "
                "categorias, forca_tipo FROM comercial_regras_percentual ORDER BY id")).fetchall()
            bases = conn.execute(text(
                "SELECT id, plataforma, valor_cobrado, valor_base, categoria, vigente_de, vigente_ate "
                "FROM comercial_valores_base ORDER BY id")).fetchall()
            parts = conn.execute(text(
                "SELECT id, beneficiario, pct_ativa, pct_reativa, vigente_de, vigente_ate, beneficiario_codigo "
                "FROM comercial_participacoes ORDER BY id")).fetchall()
            atrib = conn.execute(text(
                "SELECT transacao, vendedor_codigo FROM comercial_atribuicoes "
                "WHERE status = 'aprovada'")).fetchall()
            ofertas = conn.execute(text(
                "SELECT codigo_do_preco, nome_deste_preco FROM comercial_ofertas")).fetchall()
    except Exception as e:
        if tabela_comercial_ausente(e):
            logger.warning("ler_cadastros: tabelas comercial_* ainda não existem; devolvendo vazio")
            return Cadastros()
        logger.exception("ler_cadastros: falha")
        raise
    return Cadastros(
        vendedores={r[0]: r[1] for r in vend},
        regras=[_regra_da_linha(r) for r in regras],
        valores_base=[ValorBase(*r) for r in bases],
        participacoes=[Participacao(*r) for r in parts],
        atribuicoes={r[0]: r[1] for r in atrib},
        ofertas={r[0]: r[1] for r in ofertas},
    )


def garantir_vendedor(codigo: str) -> str:
    """Devolve o nome do vendedor; se não existir, cria 'Vendedor N' (criado_auto=True)."""
    codigo = codigo.upper()
    numero = codigo.removeprefix("AT")
    with _get_users_engine().begin() as conn:
        conn.execute(text(
            "INSERT INTO comercial_vendedores (codigo, nome, ativo, criado_auto) "
            "VALUES (:c, :n, true, true) ON CONFLICT (codigo) DO NOTHING"),
            {"c": codigo, "n": f"Vendedor {numero}"})
        return conn.execute(text("SELECT nome FROM comercial_vendedores WHERE codigo = :c"),
                            {"c": codigo}).scalar_one()


