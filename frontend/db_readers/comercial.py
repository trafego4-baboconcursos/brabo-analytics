class EscritaRecusada(Exception):
    """Pedido válido, mas o estado do banco não deixa (ex.: já aprovada). `codigo` vai na URL."""

    def __init__(self, codigo: str):
        super().__init__(codigo)
        self.codigo = codigo


@contextmanager
def _transacao(conn):
    if conn is not None:
        yield conn
        return
    with _get_users_engine().begin() as c:
        yield c


def _gravar(conn, sql: str, params: dict):
    exigir_so_comercial(sql)
    return conn.execute(text(sql), params)


def _historico(conn, tabela: str, registro_id: str, campo: str, antes, depois, por: str) -> None:
    _gravar(conn, SQL_HISTORICO_INSERIR, {
        "tabela": tabela, "registro_id": registro_id, "campo": campo,
        "antes": None if antes is None else str(antes), "depois": None if depois is None else str(depois),
        "por": por})


def _chave(plataforma: str, transacao: str) -> dict:
    return {"plataforma": plataforma, "transacao": transacao}


def reivindicar(transacao: str, plataforma: str, vendedor_codigo: str, por: str, *, conn=None) -> None:
    """Pedido de atribuição (status pendente). Não mexe no cálculo até o gestor aprovar."""
    with _transacao(conn) as c:
        atual = c.execute(text(SQL_ATRIB_LER), _chave(plataforma, transacao)).fetchone()
        if atual is not None:
            raise EscritaRecusada({"aprovada": "ja_atribuida", "pendente": "ja_reivindicada",
                                   "recusada": "ja_recusada"}.get(atual[0], "ja_reivindicada"))
        r = _gravar(c, SQL_ATRIB_REIVINDICAR, {**_chave(plataforma, transacao),
                                                "vendedor_codigo": vendedor_codigo, "por": por})
        if r.rowcount == 0:  # outro pedido entrou entre a leitura e o INSERT
            raise EscritaRecusada("ja_reivindicada")
        _historico(c, "comercial_atribuicoes", f"{plataforma}:{transacao}", "status",
                   None, f"pendente ({vendedor_codigo})", por)


def decidir_atribuicao(transacao: str, plataforma: str, aprovar: bool, por: str,
                       motivo: str | None = None, *, conn=None) -> str:
    """pendente -> aprovada | recusada. Idempotente: 0 linhas = já decidida (nada duplica).
    Devolve o código do vendedor."""
    with _transacao(conn) as c:
        atual = c.execute(text(SQL_ATRIB_LER), _chave(plataforma, transacao)).fetchone()
        if atual is None:
            raise EscritaRecusada("nao_encontrada")
        sql = SQL_ATRIB_APROVAR if aprovar else SQL_ATRIB_RECUSAR
        params = {**_chave(plataforma, transacao), "por": por}
        if not aprovar:
            params["motivo"] = motivo
        r = _gravar(c, sql, params)
        if r.rowcount == 0:
            raise EscritaRecusada("ja_aprovada" if atual[0] == "aprovada" else
                                  "ja_recusada" if atual[0] == "recusada" else "ja_decidida")
        novo = "aprovada" if aprovar else "recusada"
        _historico(c, "comercial_atribuicoes", f"{plataforma}:{transacao}", "status",
                   f"pendente ({atual[1]})", f"{novo} ({atual[1]})" + ("" if aprovar else f": {motivo}"), por)
        return atual[1]


def atribuir_gestor(transacao: str, plataforma: str, vendedor_codigo: str, por: str,
                    motivo: str | None = None, *, conn=None) -> None:
    """Gestor atribui direto (aprovada). Cobre venda sem código, conflito TMB e pedido
    pendente/recusado; atribuição já aprovada não é sobrescrita por aqui."""
    with _transacao(conn) as c:
        atual = c.execute(text(SQL_ATRIB_LER), _chave(plataforma, transacao)).fetchone()
        if atual is not None and atual[0] == "aprovada":
            raise EscritaRecusada("ja_atribuida")
        r = _gravar(c, SQL_ATRIB_GESTOR, {**_chave(plataforma, transacao),
                                           "vendedor_codigo": vendedor_codigo, "por": por, "motivo": motivo})
        if r.rowcount == 0:
            raise EscritaRecusada("ja_atribuida")
        _historico(c, "comercial_atribuicoes", f"{plataforma}:{transacao}", "status",
                   None if atual is None else f"{atual[0]} ({atual[1]})", f"aprovada ({vendedor_codigo})", por)


def decidir_reembolso(transacao: str, plataforma: str, decisao: str, justificativa: str, por: str,
                      *, conn=None) -> None:
    if decisao not in ("mantem", "tira"):
        raise ValueError("decisao deve ser 'mantem' ou 'tira'")
    with _transacao(conn) as c:
        antes = c.execute(text(SQL_REEMBOLSO_LER_UM), _chave(plataforma, transacao)).fetchone()
        _gravar(c, SQL_REEMBOLSO_UPSERT, {**_chave(plataforma, transacao), "decisao": decisao,
                                           "justificativa": justificativa, "por": por})
        _historico(c, "comercial_decisoes_reembolso", f"{plataforma}:{transacao}", "decisao",
                   None if antes is None else antes[0], f"{decisao}: {justificativa}", por)


def _txt_ajuste(pct, base) -> str:
    return f"pct={'' if pct is None else pct}; base={'' if base is None else base}"


def gravar_ajuste(transacao: str, plataforma: str, pct: Decimal | None, valor_base: Decimal | None,
                  justificativa: str, por: str, *, conn=None) -> None:
    """Desativa o ajuste ativo da venda (fica no banco, como rastro) e grava o novo."""
    if pct is None and valor_base is None:
        raise ValueError("ajuste sem pct nem valor_base")
    with _transacao(conn) as c:
        antes = c.execute(text(SQL_AJUSTE_LER_ATIVO), _chave(plataforma, transacao)).fetchone()
        _gravar(c, SQL_AJUSTE_DESATIVAR, _chave(plataforma, transacao))
        _gravar(c, SQL_AJUSTE_INSERIR, {**_chave(plataforma, transacao), "pct": pct,
                                         "valor_base": valor_base, "justificativa": justificativa, "por": por})
        _historico(c, "comercial_ajustes", f"{plataforma}:{transacao}", "ajuste",
                   None if antes is None else _txt_ajuste(*antes),
                   f"{_txt_ajuste(pct, valor_base)}: {justificativa}", por)


