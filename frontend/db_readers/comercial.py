def criar_tabelas() -> None:
    """Cria as tabelas comercial_* (idempotente). Só quem grava chama."""
    with _get_users_engine().begin() as conn:
        for ddl in DDL:
            conn.execute(text(ddl))


def ler_cadastros() -> Cadastros:
    """Cadastros vigentes. Tabela ausente -> Cadastros vazio + warning (sem DDL)."""
    try:
        with _get_users_engine().connect() as conn:
            vend = conn.execute(text("SELECT codigo, nome FROM comercial_vendedores")).fetchall()
            regras = conn.execute(text(
                "SELECT id, plataforma, modalidade, tipo, pct, vendedor_codigo, vigente_de, vigente_ate "
                "FROM comercial_regras_percentual ORDER BY id")).fetchall()
            bases = conn.execute(text(
                "SELECT id, plataforma, valor_cobrado, valor_base, categoria, vigente_de, vigente_ate "
                "FROM comercial_valores_base ORDER BY id")).fetchall()
            parts = conn.execute(text(
                "SELECT id, beneficiario, pct_ativa, pct_reativa, vigente_de, vigente_ate, beneficiario_codigo "
                "FROM comercial_participacoes ORDER BY id")).fetchall()
            atrib = conn.execute(text(
                "SELECT transacao, vendedor_codigo FROM comercial_atribuicoes "
                "WHERE status = 'aprovada'")).fetchall()
            ofertas = conn.execute(text(
                "SELECT codigo_do_preco, nome_deste_preco FROM comercial_ofertas")).fetchall()
    except Exception as e:
        if "does not exist" in str(e) and "comercial_" in str(e):
            logger.warning("ler_cadastros: tabelas comercial_* ainda não existem; devolvendo vazio")
            return Cadastros()
        logger.exception("ler_cadastros: falha")
        raise
    return Cadastros(
        vendedores={r[0]: r[1] for r in vend},
        regras=[RegraPercentual(*r) for r in regras],
        valores_base=[ValorBase(*r) for r in bases],
        participacoes=[Participacao(*r) for r in parts],
        atribuicoes={r[0]: r[1] for r in atrib},
        ofertas={r[0]: r[1] for r in ofertas},
    )


def garantir_vendedor(codigo: str) -> str:
    """Devolve o nome do vendedor; se não existir, cria 'Vendedor N' (criado_auto=True)."""
    codigo = codigo.upper()
    numero = codigo.removeprefix("AT")
    with _get_users_engine().begin() as conn:
        conn.execute(text(
            "INSERT INTO comercial_vendedores (codigo, nome, ativo, criado_auto) "
            "VALUES (:c, :n, true, true) ON CONFLICT (codigo) DO NOTHING"),
            {"c": codigo, "n": f"Vendedor {numero}"})
        return conn.execute(text("SELECT nome FROM comercial_vendedores WHERE codigo = :c"),
                            {"c": codigo}).scalar_one()


# ---------------------------------------------------------------- vendas
_SP = ZoneInfo("America/Sao_Paulo")
_HM_PAGO = {"COMPLETO", "COMPLETED", "APROVADO", "APPROVED"}
_HM_CANCELA = {"CANCELADO", "CANCELED", "REEMBOLSADO", "REFUNDED", "CHARGEBACK"}
_RE_BR = re.compile(r"^(\d{2})/(\d{2})/(\d{4})(?:[ T](\d{2}):(\d{2})(?::(\d{2}))?)?")


def _para_sp(dt: datetime) -> datetime:
    """Aware -> naive em São Paulo; naive fica como está (já local)."""
    if dt.tzinfo is None:
        return dt
    return dt.astimezone(_SP).replace(tzinfo=None)


def _data_local(valor) -> datetime | None:
    """`data_da_transacao` (texto, 3 formatos) -> datetime naive em São Paulo."""
    if valor is None:
        return None
    s = str(valor).strip()
    if not s:
        return None
    try:
        if s.isdigit() and len(s) in (10, 13):
            seg = int(s) / 1000 if len(s) == 13 else int(s)
            return _para_sp(datetime.fromtimestamp(seg, tz=timezone.utc))
        m = _RE_BR.match(s)
        if m:
            d, mo, a, h, mi, se = m.groups()
            return datetime(int(a), int(mo), int(d), int(h or 0), int(mi or 0), int(se or 0))
        if re.match(r"^\d{4}-\d{2}-\d{2}", s):
            return _para_sp(datetime.fromisoformat(s.replace("Z", "+00:00")))
    except (ValueError, OverflowError):
        return None
    return None


def _dec(valor) -> Decimal | None:
    try:
        d = Decimal(str(valor).strip())
    except (InvalidOperation, ValueError):
        return None
    return d if d.is_finite() else None


def _valor_export(l: dict) -> Decimal | None:
    """"Valor de compra sem impostos" do export da Hotmart (= VLR ENTRADA da planilha, chave
    da tabela de valores-base). Linha antiga (export CSV, com `faturamento_liquido`): é o próprio
    `valor_de_compra_sem_impostos`. Linha do webhook/API (sem `faturamento_liquido`): o banco
    grava o líquido da taxa de processamento, então soma `taxa_de_processamento` de volta
    (METODOLOGIA_EXTRACAO_DADOS §15)."""
    sem = _dec(l.get("valor_de_compra_sem_impostos"))
    if sem is None:
        return None
    if l.get("faturamento_liquido") not in (None, ""):
        return sem
    taxa = _dec(l.get("taxa_de_processamento")) if l.get("taxa_de_processamento") not in (None, "") else None
    return sem + taxa if taxa is not None else sem


def normalizar_hotmart(linhas: list[dict], ofertas: dict[str, str] | None = None) -> list[Venda]:
    """Agrupa por transação; só 1ª cobrança; nome nulo -> `ofertas[codigo_do_preco]`."""
    ofertas = ofertas or {}
    grupos: dict[str, list[dict]] = {}
    for l in linhas:
        grupos.setdefault(l["codigo_da_transacao"], []).append(l)
    out: list[Venda] = []
    ignoradas = 0
    for tid, g in grupos.items():
        if any((l.get("quantidade_de_cobrancas") or 1) > 1 for l in g):
            continue
        status = [str(l.get("status_da_transacao") or "").strip().upper() for l in g]
        pago = any(s in _HM_PAGO for s in status)
        rep = next((l for l, s in zip(g, status) if s in _HM_PAGO), g[0])
        data = _data_local(rep.get("data_da_transacao"))
        valor = _valor_export(rep)
        if data is None or valor is None:
            ignoradas += 1
            continue
        oferta = next((l["nome_deste_preco"] for l in g if l.get("nome_deste_preco")), None)
        if not oferta:
            oferta = next((ofertas[l["codigo_do_preco"]] for l in g
                           if l.get("codigo_do_preco") in ofertas), "")
        cancelada = None
        if any(s in _HM_CANCELA for s in status):
            ev = next((l["ultimo_evento_em"] for l in g if l.get("ultimo_evento_em")), None)
            cancelada = _para_sp(ev) if ev else data
        out.append(Venda(
            plataforma="hotmart", transacao=tid, data=data,
            produto_id=str(rep.get("codigo_do_produto") or ""), produto=rep.get("produto") or "",
            oferta=oferta, codigo_at=extrair_codigo_at(oferta), conflito_codigo=False,
            modalidade=modalidade_hotmart(rep.get("tipo_de_cobranca"), rep.get("metodo_de_pagamento")),
            categoria=None, valor_cobrado=valor, pago=pago, cancelada_em=cancelada))
    if ignoradas:
        logger.warning("normalizar_hotmart: %d transações sem data/valor legível ignoradas", ignoradas)
    return out


def normalizar_tmb(linhas: list[dict]) -> list[Venda]:
    out: list[Venda] = []
    ignoradas = 0
    for l in linhas:
        pedido = str(l.get("pedido") or "")
        if pedido.upper() == "TESTE":
            continue
        valor = _dec(l.get("ticket"))
        data = _data_local(l.get("data_efetivado"))
        if valor is None or data is None or not pedido:
            ignoradas += 1
            continue
        a = extrair_codigo_at(l.get("utm_content"))
        b = extrair_codigo_at(l.get("utm_last_content"))
        conflito = bool(a and b and a != b)
        canc = l.get("data_cancelamento")
        lanc = l.get("lancamento_id")
        out.append(Venda(
            plataforma="tmb", transacao=pedido, data=data,
            produto_id="" if lanc is None else str(lanc), produto=l.get("produto") or "",
            oferta=l.get("oferta") or "", codigo_at=None if conflito else (a or b),
            conflito_codigo=conflito, modalidade="parcelado",
            categoria=categoria_tmb(l.get("utm_campaign"), l.get("oferta")),
            valor_cobrado=valor, pago=l.get("status") == "Efetivado",
            cancelada_em=_para_sp(canc) if canc else None))
    if ignoradas:
        logger.warning("normalizar_tmb: %d pedidos sem ticket/data legível ignorados", ignoradas)
    return out


_COLS_HM = ("h.codigo_da_transacao, h.status_da_transacao, h.data_da_transacao, h.codigo_do_produto, "
            "h.produto, h.codigo_do_preco, h.nome_deste_preco, h.tipo_de_cobranca, "
            "h.metodo_de_pagamento, h.quantidade_de_cobrancas, h.valor_de_compra_sem_impostos, "
            "h.taxa_de_processamento, h.faturamento_liquido, e.ultimo_evento_em")
_CHAVES_HM = [c.strip().split(".")[-1] for c in _COLS_HM.split(",")]
_SQL_HOTMART_PERIODO = r"""
    SELECT """ + _COLS_HM + r"""
    FROM (
        SELECT *, CASE WHEN NULLIF(data_da_transacao,'') ~ '^\d{2}/\d{2}/\d{4}'
                           THEN substr(data_da_transacao,7,4)||substr(data_da_transacao,4,2)||substr(data_da_transacao,1,2)
                       WHEN NULLIF(data_da_transacao,'') ~ '^\d{10,13}$'
                           THEN to_char(to_timestamp(CASE WHEN length(data_da_transacao) = 13
                                                          THEN data_da_transacao::bigint / 1000
                                                          ELSE data_da_transacao::bigint END)
                                        AT TIME ZONE 'America/Sao_Paulo', 'YYYYMMDD')
                       WHEN data_da_transacao ~ '^\d{4}-\d{2}-\d{2}'
                           THEN replace(substr(data_da_transacao,1,10),'-','')
                       ELSE NULL END AS _data_aprox
        FROM hotmart_oficial
    ) h
    LEFT JOIN hotmart_estado_transacao e ON e.codigo_da_transacao = h.codigo_da_transacao
    WHERE h._data_aprox BETWEEN :d_ini AND :d_fim
       -- formato desconhecido sobe para o Python contar no warning
       OR (h._data_aprox IS NULL AND NULLIF(TRIM(h.data_da_transacao), '') IS NOT NULL)
"""
_SQL_HOTMART_EXTRA = ("SELECT " + _COLS_HM + " FROM hotmart_oficial h "
                      "LEFT JOIN hotmart_estado_transacao e ON e.codigo_da_transacao = h.codigo_da_transacao "
                      "WHERE h.codigo_da_transacao = ANY(:extra)")
_SQL_NOMES = """
    SELECT codigo_do_preco, nome_deste_preco, count(*) FROM hotmart_oficial
    WHERE codigo_do_preco = ANY(:codigos) AND nome_deste_preco IS NOT NULL AND nome_deste_preco <> ''
    GROUP BY 1, 2
"""
_SQL_TMB = r"""
    SELECT pedido, status, status_cancelamento, data_efetivado, data_cancelamento, ticket, produto,
           oferta, utm_campaign, utm_content, utm_last_content, lancamento_id
    FROM (
        SELECT *, CASE WHEN TRIM(data_efetivado) ~ '^\d{2}/\d{2}/\d{4}'
                           THEN substr(TRIM(data_efetivado),7,4)||substr(TRIM(data_efetivado),4,2)||substr(TRIM(data_efetivado),1,2)
                       WHEN TRIM(data_efetivado) ~ '^\d{10,13}$'
                           THEN to_char(to_timestamp(CASE WHEN length(TRIM(data_efetivado)) = 13
                                                          THEN TRIM(data_efetivado)::bigint / 1000
                                                          ELSE TRIM(data_efetivado)::bigint END)
                                        AT TIME ZONE 'America/Sao_Paulo', 'YYYYMMDD')
                       WHEN TRIM(data_efetivado) ~ '^\d{4}-\d{2}-\d{2}'
                           THEN replace(substr(TRIM(data_efetivado),1,10),'-','')
                       ELSE NULL END AS _data_aprox
        FROM tmb_oficial
    ) t
    WHERE pedido = ANY(:extra)
       OR _data_aprox BETWEEN :d_ini AND :d_fim
       -- formato desconhecido: sobe para o Python contar no warning (nada some em silêncio)
       OR (_data_aprox IS NULL AND NULLIF(TRIM(data_efetivado), '') IS NOT NULL)
"""


def _filtrar_periodo(vendas: list[Venda], inicio: date, fim: date,
                     extra: frozenset[str] | set[str], incluir_extra_fora: bool) -> list[Venda]:
    """Vendas do período; as `extra` de fora do período só ficam se `incluir_extra_fora`."""
    return [v for v in vendas
            if inicio <= v.data.date() <= fim or (incluir_extra_fora and v.transacao in extra)]


def ler_vendas(inicio: date, fim: date, transacoes_extra: frozenset[str] = frozenset(),
               ofertas: dict[str, str] | None = None, *,
               incluir_extra_fora_do_periodo: bool = False) -> list[Venda]:
    """Vendas Hotmart+TMB do período [inicio, fim] (todas, com ou sem código AT). As
    `transacoes_extra` (atribuídas à mão) só entram se estiverem no período — a menos que
    `incluir_extra_fora_do_periodo` (uso da conciliação, que as sinaliza). Só SELECT."""
    extra = sorted(transacoes_extra)
    params = {"d_ini": (inicio - timedelta(days=1)).strftime("%Y%m%d"),
              "d_fim": (fim + timedelta(days=1)).strftime("%Y%m%d"), "extra": extra}
    with _get_users_engine().begin() as conn:
        conn.execute(text("SET LOCAL statement_timeout = '120s'"))
        hm = [dict(zip(_CHAVES_HM, r)) for r in conn.execute(text(_SQL_HOTMART_PERIODO), params).fetchall()]
        if extra:
            ja = {l["codigo_da_transacao"] for l in hm}
            hm += [dict(zip(_CHAVES_HM, r))
                   for r in conn.execute(text(_SQL_HOTMART_EXTRA), {"extra": extra}).fetchall()
                   if r[0] not in ja]
        sem_nome = sorted({l["codigo_do_preco"] for l in hm
                           if not l["nome_deste_preco"] and l["codigo_do_preco"]})
        if sem_nome:
            freq: dict[str, Counter] = {}
            for cod, nome, n in conn.execute(text(_SQL_NOMES), {"codigos": sem_nome}).fetchall():
                freq.setdefault(cod, Counter())[nome] += n
            nomes = {c: ct.most_common(1)[0][0] for c, ct in freq.items()}
            for l in hm:
                if not l["nome_deste_preco"] and l["codigo_do_preco"] in nomes:
                    l["nome_deste_preco"] = nomes[l["codigo_do_preco"]]
        tm_rows = conn.execute(text(_SQL_TMB), params).mappings().fetchall()
    vendas = normalizar_hotmart(hm, ofertas) + normalizar_tmb([dict(r) for r in tm_rows])
    return _filtrar_periodo(vendas, inicio, fim, set(extra), incluir_extra_fora_do_periodo)


